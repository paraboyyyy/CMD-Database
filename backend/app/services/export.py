"""Write stored structures (pymatgen Structure.as_dict() layout) as CIF, POSCAR, XYZ or JSON.

Kept free of pymatgen so the API stays small enough for serverless hosting.
"""

from __future__ import annotations

import json

EXPORT_FORMATS = {
    "cif": ("chemical/x-cif", "cif"),
    "poscar": ("text/plain", "vasp"),
    "xyz": ("chemical/x-xyz", "xyz"),
    "json": ("application/json", "json"),
}


def _element(site: dict) -> str:
    return max(site["species"], key=lambda s: s["occu"])["element"]


def to_cif(structure: dict, lattice: dict, name: str) -> str:
    lines = [
        "# Generated by CMD Database",
        f"data_{name}",
        "_symmetry_space_group_name_H-M   'P 1'",
        "_symmetry_Int_Tables_number      1",
        *(f"_cell_length_{k:<5s}  {lattice[k]:.6f}" for k in ("a", "b", "c")),
        *(f"_cell_angle_{k:<5s}   {lattice[k]:.6f}" for k in ("alpha", "beta", "gamma")),
        "loop_",
        "_symmetry_equiv_pos_as_xyz",
        "  'x, y, z'",
        "loop_",
        "_atom_site_label",
        "_atom_site_type_symbol",
        "_atom_site_fract_x",
        "_atom_site_fract_y",
        "_atom_site_fract_z",
        "_atom_site_occupancy",
    ]
    counts: dict[str, int] = {}
    for site in structure["sites"]:
        for sp in site["species"]:
            el = sp["element"]
            counts[el] = counts.get(el, 0) + 1
            x, y, z = site["abc"]
            lines.append(f"  {el}{counts[el]}  {el}  {x:.6f}  {y:.6f}  {z:.6f}  {sp['occu']:g}")
    return "\n".join(lines) + "\n"


def to_poscar(structure: dict, name: str) -> str:
    sites = structure["sites"]
    order: list[str] = []
    for site in sites:
        if (el := _element(site)) not in order:
            order.append(el)
    grouped = {el: [s for s in sites if _element(s) == el] for el in order}
    lines = [name, "1.0"]
    lines += ["  " + "  ".join(f"{v:.10f}" for v in row) for row in structure["lattice"]["matrix"]]
    lines += ["  " + "  ".join(order), "  " + "  ".join(str(len(grouped[el])) for el in order), "Direct"]
    for el in order:
        lines += [f"  {s['abc'][0]:.10f}  {s['abc'][1]:.10f}  {s['abc'][2]:.10f}  {el}" for s in grouped[el]]
    return "\n".join(lines) + "\n"


def to_xyz(structure: dict, name: str) -> str:
    sites = structure["sites"]
    m = structure["lattice"]["matrix"]
    lattice = " ".join(f"{v:.8f}" for row in m for v in row)
    lines = [str(len(sites)), f'Lattice="{lattice}" Properties=species:S:1:pos:R:3 name={name}']
    lines += [f"{_element(s)}  {s['xyz'][0]:.8f}  {s['xyz'][1]:.8f}  {s['xyz'][2]:.8f}" for s in sites]
    return "\n".join(lines) + "\n"


def export(structure: dict, lattice: dict, fmt: str, name: str) -> str:
    if fmt == "cif":
        return to_cif(structure, lattice, name)
    if fmt == "poscar":
        return to_poscar(structure, name)
    if fmt == "xyz":
        return to_xyz(structure, name)
    if fmt == "json":
        return json.dumps(structure)
    raise ValueError(f"Unknown format {fmt}")
