import { type Crystal, cartToFrac, latticeParams, wrap01 } from "./structure";

const n = (x: number, d = 8) => (Object.is(x, -0) ? 0 : x).toFixed(d);

/** P1 CIF of a periodic crystal. */
export function toCif(c: Crystal, name: string): string {
  const m = c.lattice!;
  const p = latticeParams(m);
  const counts = new Map<string, number>();
  const rows = c.atoms.map((a) => {
    const k = (counts.get(a.element) ?? 0) + 1;
    counts.set(a.element, k);
    const f = cartToFrac(a.cart, m).map((x) => wrap01(x, 1e-8));
    return `  ${a.element}${k}  ${a.element}  ${n(f[0])}  ${n(f[1])}  ${n(f[2])}  1`;
  });
  return [
    "# Generated by CMD Database",
    `data_${name.replace(/\s+/g, "_")}`,
    "_symmetry_space_group_name_H-M   'P 1'",
    "_symmetry_Int_Tables_number      1",
    `_cell_length_a    ${n(p.a, 6)}`,
    `_cell_length_b    ${n(p.b, 6)}`,
    `_cell_length_c    ${n(p.c, 6)}`,
    `_cell_angle_alpha ${n(p.alpha, 6)}`,
    `_cell_angle_beta  ${n(p.beta, 6)}`,
    `_cell_angle_gamma ${n(p.gamma, 6)}`,
    "loop_",
    "_symmetry_equiv_pos_as_xyz",
    "  'x, y, z'",
    "loop_",
    "_atom_site_label",
    "_atom_site_type_symbol",
    "_atom_site_fract_x",
    "_atom_site_fract_y",
    "_atom_site_fract_z",
    "_atom_site_occupancy",
    ...rows,
    "",
  ].join("\n");
}

/** VASP 5 POSCAR with direct coordinates, atoms grouped by element. */
export function toPoscar(c: Crystal, name: string): string {
  const m = c.lattice!;
  const order = [...new Set(c.atoms.map((a) => a.element))];
  const lines = [name, "1.0", ...m.map((v) => `  ${v.map((x) => n(x, 10)).join("  ")}`)];
  lines.push(`  ${order.join("  ")}`, `  ${order.map((el) => c.atoms.filter((a) => a.element === el).length).join("  ")}`, "Direct");
  for (const el of order)
    for (const a of c.atoms.filter((x) => x.element === el)) {
      const f = cartToFrac(a.cart, m).map((x) => wrap01(x, 1e-8));
      lines.push(`  ${f.map((x) => n(x, 10)).join("  ")}  ${el}`);
    }
  return lines.join("\n") + "\n";
}

/** Extended XYZ (keeps the lattice). */
export function toXyz(c: Crystal, name: string): string {
  const lattice = c.lattice ? ` Lattice="${c.lattice.flat().map((x) => n(x)).join(" ")}" pbc="T T T"` : "";
  return [
    String(c.atoms.length),
    `${lattice.trim()} Properties=species:S:1:pos:R:3 name=${name.replace(/\s+/g, "_")}`.trim(),
    ...c.atoms.map((a) => `${a.element}  ${a.cart.map((x) => n(x)).join("  ")}`),
    "",
  ].join("\n");
}

export function downloadText(text: string, filename: string) {
  const url = URL.createObjectURL(new Blob([text], { type: "text/plain" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
